import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 1300 } })
const errs = []; page.on('pageerror', e => errs.push(e.message))
const results = []
const ok = (name, condition) => results.push(`${condition ? 'PASS' : 'FAIL'}  ${name}`)
await page.goto(process.env.PROTOTYPE_URL || 'http://127.0.0.1:5180/', { waitUntil: 'networkidle' })
await page.locator('[data-testid="audit"]').click()
await page.waitForTimeout(500)
const M = () => page.locator('#AppFrameMain').first().innerText()
let t = await M()
ok('初始一致', t.includes('全部一致'))
ok('快照含店铺、检查时间与配置版本', t.includes('nordwind-supply.myshopify.com') && t.includes('检查于 2026-10-25 15:38') && t.includes('配置版本 1'))
ok('快照含四个告知位置状态', ['全站页脚横条', '商品页区块', '购物车页', '购物车抽屉'].every((s) => t.includes(s)) && t.includes('已开启 1 / 4 个位置'))
ok('快照含语言、声明与五状态覆盖', t.includes('欧盟全部 24 种官方语言') && t.includes('Free 套餐未启用声明交付') && t.includes('不符合条件 1') && t.includes('未审阅 3'))
ok('快照含全部排除原因与商品明细', ['数字商品', '礼品卡', 'B2B 与批发', '自定义标签', '手动排除', '批发托盘 — 24 件', '备用零件包'].every((s) => t.includes(s)))
ok('未把快照误标为合规保证', t.includes('不构成合规保证或法律意见'))
await page.getByRole('button', { name: '展开全部 24 种语言' }).click()
await page.waitForTimeout(350)
t = await M()
ok('24 种语言可展开且含中英文语言名', t.includes('英语 (EN)') && t.includes('马耳他语 (MT)'))
ok('历史使用 Tab 而非下拉选择', await page.getByRole('tab', { name: '全部', exact: true }).count() === 1 && await page.locator('main select').count() === 0)
await page.getByRole('tab', { name: 'GARAN 标签', exact: true }).click()
await page.waitForTimeout(300)
t = await M()
ok('历史可通过 Tab 筛选为 GARAN 标签', t.includes('2 / 3 条记录') && t.includes('标签已保存') && t.includes('写入被拒') && !t.includes('告知已开启'))
await page.getByRole('tab', { name: '导出', exact: true }).click()
await page.waitForTimeout(300)
t = await M()
ok('无导出历史时显示空状态', t.includes('0 / 3 条记录') && t.includes('该类型暂无记录'))
await page.getByRole('tab', { name: '全部', exact: true }).click()
await page.waitForTimeout(250)
await page.screenshot({ path: '/tmp/p-audit-clean.png', fullPage: true })

await page.getByRole('button', { name: '模拟一处矛盾' }).click()
await page.waitForTimeout(600)
t = await M()
ok('注入后检出冲突', /项矛盾/.test(t))
ok('冲突清单列出礼品卡', t.includes('礼品卡'))
ok('有矛盾时快照不显示全部一致', t.includes('需先修复'))
await page.screenshot({ path: '/tmp/p-audit-conflict.png', fullPage: true })

// 导出应被阻止
await page.getByRole('button', { name: '导出快照（PDF）' }).click()
await page.waitForTimeout(500)
const modal = await page.locator('[role="dialog"]').innerText()
ok('T5e 导出被阻止', modal.includes('导出被阻止'))
await page.screenshot({ path: '/tmp/p-audit-blocked.png' })
console.log(results.join('\n'))
console.log('\n=== errors ===')
console.log(errs.length ? errs.join('\n') : '(none)')
console.log(`\n${results.filter((r) => r.startsWith('PASS')).length}/${results.length} passed`)
await browser.close()
if (results.some((r) => r.startsWith('FAIL')) || errs.length) process.exitCode = 1
